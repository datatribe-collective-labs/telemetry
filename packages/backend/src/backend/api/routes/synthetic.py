@router.get("/state", response_model=SyntheticStateResponse)
async def list_synthetic_state(
    db: Annotated[Session, Depends(get_db)],
    date_from: datetime | None = Query(None, description="Start date (UTC)"),
    date_to: datetime | None = Query(None, description="End date (UTC)"),
    limit: int = Query(100, ge=1, le=1000, description="Maximum results"),
    offset: int = Query(0, ge=0, description="Pagination offset"),
) -> SyntheticStateResponse:
    """List synthetic state snapshots from the state engine.
    
    This replaces AROW attitude telemetry - the authoritative per-tick
    spacecraft state derived from JPL Horizons ephemeris and OEM files.
    """
    conditions = []
    params: dict = {}

    if date_from:
        conditions.append("timestamp_utc >= :date_from")
        params["date_from"] = date_from
    if date_to:
        conditions.append("timestamp_utc < :date_to")
        params["date_to"] = date_to

    where_clause = _build_where_clause(conditions)
    total = _count_query(db, "state_snapshot", where_clause, params)
    items = _execute_query(db, "state_snapshot", STATE_COLUMNS, where_clause, params, limit, offset)

    return SyntheticStateResponse(
        items=[SyntheticStateSnapshot.model_validate(item) for item in items],
        total=total,
        limit=limit,
        offset=offset,
    )


@router.get("/state/{timestamp_utc}", response_model=SyntheticStateSnapshot)
async def get_synthetic_state(
    timestamp_utc: datetime,
    db: Annotated[Session, Depends(get_db)],
) -> SyntheticStateSnapshot:
    """Get a specific state snapshot by timestamp."""
    columns_str = _select_columns(STATE_COLUMNS)
    query = f"SELECT {columns_str} FROM state_snapshot WHERE timestamp_utc = :timestamp_utc"
    result = db.execute(text(query), {"timestamp_utc": timestamp_utc})
    row = result.first()
    if not row:
        raise HTTPException(status_code=404, detail="State snapshot not found")
    return SyntheticStateSnapshot.model_validate(dict(row._mapping))


