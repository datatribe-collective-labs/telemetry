# =============================================================================
# Helper functions
# =============================================================================

def _build_where_clause(conditions: list[str]) -> str:
    """Build WHERE clause from conditions list."""
    return "WHERE " + " AND ".join(conditions) if conditions else ""


def _select_columns(contract_columns: list[str]) -> str:
    """
    Build SELECT list: lowercase DB column AS "ContractName".
    
    DB columns are lowercase snake_case; contract fields preserve original case.
    If a column already contains ' AS ', it's treated as a pre-formatted expression.
    """
    result = []
    for c in contract_columns:
        if " AS " in c:
            # Pre-formatted expression (e.g., "event_id::text AS \"event_id\"")
            result.append(c)
        else:
            result.append(f"{c.lower()} AS \"{c}\"")
    return ", ".join(result)


def _verify_lowercase(columns: list[str], context: str) -> None:
    """Verify all column names are lowercase (for WHERE/ORDER BY)."""
    for c in columns:
        if c != c.lower():
            raise ValueError(f"Column '{c}' in {context} is not lowercase")


def _execute_query(
    db: Session,
    table: str,
    contract_columns: list[str],
    where_clause: str,
    params: dict,
    limit: int,
    offset: int,
    order_by: str = "timestamp_utc",
) -> list:
    """Execute a SELECT query with pagination."""
    # Verify order_by is lowercase
    _verify_lowercase([order_by], "order_by")
    
    columns_str = _select_columns(contract_columns)
    query = f"""
        SELECT {columns_str}
        FROM {table}
        {where_clause}
        ORDER BY {order_by}
        LIMIT :limit OFFSET :offset
    """
    params["limit"] = limit
    params["offset"] = offset
    result = db.execute(text(query), params)
    return [dict(row._mapping) for row in result]


def _count_query(db: Session, table: str, where_clause: str, params: dict) -> int:
    """Execute a COUNT query."""
    query = f"SELECT COUNT(*) FROM {table} {where_clause}"
    return db.execute(text(query), params).scalar() or 0


